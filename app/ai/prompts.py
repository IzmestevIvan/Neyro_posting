def _language_line(lang: str) -> str:
    return f"Пиши на языке: {LANGUAGES.get(lang, lang)}."


def triage_prompt(text: str, instructions: str) -> str:
    wishes = instructions.strip() or "особых пожеланий нет"
    return f"""Оцени ЧУЖОЙ пост и реши, годится ли он как исходник для пересказа.

ПОЖЕЛАНИЯ ВЛАДЕЛЬЦА КАНАЛА:
{wishes}

ВАЖНО про пожелания. В них перемешаны два разных вида требований:
1. ТЕМАТИКА — о чём канал («новости Москвы», «только про финансы»). Только это относится
   к твоему решению.
2. ОФОРМЛЕНИЕ — тон, длина, смайлики, язык, структура («начинай со смайлика», «не длиннее
   180 слов», «без эмодзи»). Это правила будущего пересказа, а НЕ требования к исходнику.
   Исходник почти никогда им не соответствует — это нормально и не повод его отбраковывать.

ПОСТ:
\"\"\"{text[:4000]}\"\"\"

Верни JSON:
{{
  "is_ad": true/false,          // реклама, промо, партнёрский материал или призыв купить
  "is_offtopic": true/false,    // ТЕМА поста не относится к тематике канала
  "is_newsworthy": true/false,  // есть содержательный информационный повод
  "topic": "короткая тема в 2-3 словах",
  "reason": "одно предложение почему"
}}

Правила:
- is_offtopic ставь true только из-за ТЕМЫ. Если про тематику ничего не сказано — всегда false.
- Никогда не отбраковывай пост за оформление: за отсутствие смайлика, за длину, за стиль,
  за язык. Всё это задаётся на следующем шаге, при пересказе.
- Сомневаешься — пропускай: владелец увидит пост на модерации."""


def rewrite_prompt(
    text: str,
    *,
    instructions: str,
    lang: str,
    voice_sample: str = "",
    deep: bool = False,
) -> str:
    blocks = [
        "Перепиши новость для моего Telegram-канала.",
        "",
        "ЖЁСТКИЕ ПРАВИЛА:",
        "- Никаких новых фактов, цифр, имён, дат, цитат и выводов, которых нет в оригинале.",
        "- Если в оригинале чего-то нет — этого нет и в твоём тексте.",
        "- Переформулируй полностью: не копируй предложения оригинала целиком.",
        "- Убери упоминания чужого канала, призывы подписаться, ссылки и рекламные хвосты.",
        "- Без markdown-заголовков и без служебных комментариев. Только готовый пост.",
        f"- {_language_line(lang)}",
    ]
    if deep:
        blocks += [
            "- Сохрани причинно-следственные связи и контекст: читатель должен понять суть без оригинала.",
            "- Если в оригинале есть цифры — перепроверь, что ты перенёс их без искажений.",
        ]
    if instructions.strip():
        blocks += ["", "ПОЖЕЛАНИЯ ВЛАДЕЛЬЦА КАНАЛА (важнее стиля по умолчанию):", instructions.strip()]
    if voice_sample.strip():
        blocks += [
            "",
            "ПРИМЕРЫ ПОСТОВ ЭТОГО КАНАЛА — подражай тону, длине и подаче, но не копируй содержание:",
            voice_sample.strip()[:2500],
        ]
    blocks += ["", "ОРИГИНАЛ:", f'"""{text[:6000]}"""']
    return "\n".join(blocks)


def factcheck_prompt(original: str, rewritten: str) -> str:
    return f"""Сравни переписанный пост с оригиналом.

ОРИГИНАЛ:
\"\"\"{original[:5000]}\"\"\"

ПЕРЕПИСАННЫЙ ТЕКСТ:
\"\"\"{rewritten[:5000]}\"\"\"

Проверь: не появились ли факты, числа, имена, должности, даты, географические привязки или
цитаты, которых нет в оригинале; не искажён ли смысл; не приписано ли кому-то утверждение.

Верни JSON:
{{
  "ok": true/false,               // true, если выдумок и искажений нет
  "hallucinations": ["конкретная выдумка", ...],
  "distortions": ["конкретное искажение смысла", ...],
  "verdict": "одно предложение"
}}"""


def digest_prompt(items: list[str], instructions: str, lang: str) -> str:
    body = "\n\n".join(f"{i + 1}. {t[:600]}" for i, t in enumerate(items))
    wishes = instructions.strip() or "особых пожеланий нет"
    return f"""Собери из этих новостей одну короткую вечернюю сводку для Telegram-канала.

ПРАВИЛА:
- Только факты из списка ниже, ничего не добавляй от себя.
- Каждая новость — один пункт в одну-две строки.
- В начале короткий заголовок сводки, дальше пункты.
- {_language_line(lang)}

ПОЖЕЛАНИЯ ВЛАДЕЛЬЦА КАНАЛА:
{wishes}

НОВОСТИ:
{body}"""


